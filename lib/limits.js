/**
 * 一次调用可以要到的硬上限。
 *
 * schema 卡的是保存下来的默认值，工具卡的是每次调用的参数，配置页镜像同一组数字，保存才不会
 * 被拒。放在一处是为了只有一个值；页面没法 import 这个文件（普通脚本没有 ESM import），所以
 * 它那份副本由一条测试比对。
 */

/** 结果条数的硬上限。 */
export const MAX_LIMIT = 100

/** 单次读取返回字符数的硬上限。 */
export const MAX_READ = 20000

/**
 * 探测的预算区间（毫秒）。
 *
 * 探测是诊断而不是检索：`timeoutMs` 很小也不能把健康引擎报成 DOWN；再大也不该让一次启动检查
 * 拖太久。两个后端共用这一对数字。
 */
export const PROBE_MIN_MS = 1500
export const PROBE_MAX_MS = 5000

/**
 * 启动检查失败后隔多久再探一次（毫秒）。
 *
 * 刚启动时整机最忙，Anytxt 偶尔一次超时或拒绝连接；单次失败就显示一张「后端不可达」的提示卡，
 * 而随后的工具调用却是好的。重试一次把瞬时失败消化掉。
 */
export const PROBE_RETRY_MS = 3000
